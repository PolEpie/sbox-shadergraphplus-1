
namespace PanelEvents;

internal static class MouseEventAttributes
{
	/// <summary>
	/// Cursor enters the panel
	/// </summary>
	public const string OnMouseOver = "onmouseover";

	/// <summary>
	/// Cursor leaves the panel
	/// </summary>
	public const string OnMouseOut = "onmouseout";

	/// <summary>
	/// Mouse button is pressed
	/// </summary>
	public const string OnMouseDown = "onmousedown";

	/// <summary>
	/// Mouse button is released
	/// </summary>
	public const string OnMouseUp = "onmouseup";

	/// <summary>
	/// Panel is clicked
	/// </summary>
	public const string OnClick = "onclick";
}
